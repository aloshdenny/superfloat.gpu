"""S2 block variants (docs/v3_gt2n.md): name -> v3_block parameters.
python3 variants.py writes v3_variants.sv, one top module per variant."""
import os

N = 8
VARIANTS = {
    "sf16_sat16": dict(FMT=0, FRAC=15, ACC_W=16),
    "sf16_sf24":  dict(FMT=0, FRAC=19, ACC_W=24),
    "sf16_sf32":  dict(FMT=0, FRAC=23, ACC_W=32),
    "fp16_fp16":  dict(FMT=1, IN_E=5, IN_M=10, ACC_E=5, ACC_M=10),
    "fp16_fp24":  dict(FMT=1, IN_E=5, IN_M=10, ACC_E=8, ACC_M=15),
    "fp16_fp32":  dict(FMT=1, IN_E=5, IN_M=10, ACC_E=8, ACC_M=23),
    "bf16_bf16":  dict(FMT=1, IN_E=8, IN_M=7, ACC_E=8, ACC_M=7),
    "bf16_fp24":  dict(FMT=1, IN_E=8, IN_M=7, ACC_E=8, ACC_M=15),
    "bf16_fp32":  dict(FMT=1, IN_E=8, IN_M=7, ACC_E=8, ACC_M=23),
}
# The same with the FP PE's align stage registered (psum path 3 stages).
for k in [k for k in VARIANTS if VARIANTS[k]["FMT"] == 1]:
    VARIANTS[k + "_a"] = dict(VARIANTS[k], ALIGN_STAGE=1)

# Levers (round 2). m: the product written as partial-product rows, none
# dropped (the structure the truncated product uses); t: columns below
# TRUNC_K dropped, COMP = their expected value with random bits,
# sum_{c<K} (c+1) 2^c / 4, rounded; g: weight-register clock gating.
SF24, SF28, SF32 = dict(FMT=0, FRAC=19, ACC_W=24), dict(FMT=0, FRAC=23, ACC_W=28), dict(FMT=0, FRAC=23, ACC_W=32)
FP16_24A = VARIANTS["fp16_fp24_a"]
BF16_24A = VARIANTS["bf16_fp24_a"]
T24 = dict(TRUNC_K=9, COMP=1024)          # 4097 / 4
T28 = dict(TRUNC_K=6, COMP=80)            # 321 / 4
TF16 = dict(TRUNC_K=4, COMP=12)           # 49 / 4, on the 11 x 11 significands
VARIANTS.update({
    "sf16_sf24_m":   dict(SF24, TRUNC_K=0),
    "sf16_sf24_t":   dict(SF24, **T24),
    "sf16_sf24_tg":  dict(SF24, **T24, CG=1),
    "sf16_sf28":     dict(SF28),
    "sf16_sf28_t":   dict(SF28, **T28),
    "sf16_sf28_tg":  dict(SF28, **T28, CG=1),
    "sf16_sf32_m":   dict(SF32, TRUNC_K=0),
    "sf16_sf32_t":   dict(SF32, **T28),
    "sf16_sf32_tg":  dict(SF32, **T28, CG=1),
    "fp16_fp24_a_m": dict(FP16_24A, TRUNC_K=0),
    "fp16_fp24_a_t": dict(FP16_24A, **TF16),
    "fp16_fp24_a_tg": dict(FP16_24A, **TF16, CG=1),
    "bf16_fp24_a_g": dict(BF16_24A, CG=1),
})
ROUND2 = [k for k in VARIANTS if k.endswith(("_m", "_t", "_tg", "_g")) or k == "sf16_sf28"]


def widths(p):
    if p["FMT"] == 0:
        return 16, p["ACC_W"]
    return 1 + p["IN_E"] + p["IN_M"], 1 + p["ACC_E"] + p["ACC_M"]


def latency(p):
    """Register stages on the partial-sum path through one PE."""
    return 1 if p["FMT"] == 0 else 2 + p.get("ALIGN_STAGE", 0)


def write_sv(path):
    out = ["`default_nettype none", "// Generated by variants.py: one v3_block top per S2 variant.", ""]
    for name, p in VARIANTS.items():
        iw, cw = widths(p)
        params = ", ".join(f".{k}({v})" for k, v in dict(N=N, **p).items())
        out += [
            f"module blk_{name} (",
            "    input  wire clk, w_shift, w_swap,",
            f"    input  wire [{N * iw - 1}:0] a_west, w_north,",
            f"    input  wire [{N * cw - 1}:0] psum_north,",
            f"    output wire [{N * iw - 1}:0] a_east,",
            f"    output wire [{N * cw - 1}:0] psum_south",
            ");",
            f"    v3_block #({params}) u_blk (",
            "        .clk(clk), .w_shift(w_shift), .w_swap(w_swap), .a_west(a_west), .w_north(w_north),",
            "        .psum_north(psum_north), .a_east(a_east), .psum_south(psum_south));",
            "endmodule", ""]
    open(path, "w").write("\n".join(out))


if __name__ == "__main__":
    write_sv(os.path.join(os.path.dirname(os.path.abspath(__file__)), "v3_variants.sv"))
