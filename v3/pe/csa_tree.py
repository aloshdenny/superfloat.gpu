#!/usr/bin/env python3
"""
Carry-save (Wallace) reduction trees for the v3 PEs' multipliers (CT = 1 in
v3_pe.sv / fpx_align.sv): NR rows of W bits reduced level by level with 3:2
compressors (sum = a ^ b ^ c, carry = majority << 1, both kept to W bits:
the rows' total fits W bits, so the arithmetic mod 2^W is exact) to two
rows, s and c, with s + c = the rows' sum. The PE adds them with one plain
adder, which ORFS maps to a Kogge-Stone carry tree, where Yosys's own
multi-operand adds end in a ripple carry.

  python3 csa_tree.py      writes csa_trees.sv: v3_csa #(W, NR), NR 2..16
"""
import os

NRS = range(2, 17)


def tree(nr):
    lines, rows, k = [], [f"r{i}" for i in range(nr)], 0
    for i in range(nr):
        lines.append(f"    wire [W-1:0] r{i} = rows[{i}*W +: W];")
    lvl = 0
    while len(rows) > 2:
        nxt = []
        for j in range(0, len(rows) - len(rows) % 3, 3):
            a, b, c = rows[j:j + 3]
            s, cy = f"s{lvl}_{j // 3}", f"c{lvl}_{j // 3}"
            m = f"m{lvl}_{j // 3}"
            lines.append(f"    wire [W-1:0] {s} = {a} ^ {b} ^ {c};")
            lines.append(f"    wire [W-1:0] {m} = ({a} & {b}) | ({a} & {c}) | ({b} & {c});")
            lines.append(f"    wire [W-1:0] {cy} = {{{m}[W-2:0], 1'b0}};")
            nxt += [s, cy]
        nxt += rows[len(rows) - len(rows) % 3:]
        rows, lvl = nxt, lvl + 1
    lines.append(f"    assign s = {rows[0]};")
    lines.append(f"    assign c = {rows[1]};")
    return lines, lvl


def main():
    out = ["`default_nettype none",
           "// Generated by csa_tree.py: carry-save reduction of NR rows of W bits to two.", ""]
    for nr in NRS:
        body, lvl = tree(nr)
        out += [f"// {nr} rows, {lvl} levels of 3:2 compressors",
                f"module v3_csa_{nr} #(parameter W = 30) (",
                f"    input  wire [{nr}*W-1:0] rows,",
                "    output wire [W-1:0] s,",
                "    output wire [W-1:0] c",
                ");"] + body + ["endmodule", ""]
    out += ["module v3_csa #(parameter W = 30, parameter NR = 16) (",
            "    input  wire [NR*W-1:0] rows,",
            "    output wire [W-1:0] s,",
            "    output wire [W-1:0] c",
            ");",
            "    generate"]
    for i, nr in enumerate(NRS):
        out.append(f"        {'if' if i == 0 else 'else if'} (NR == {nr}) begin : g{nr} v3_csa_{nr} #(.W(W)) t (.rows(rows), .s(s), .c(c)); end")
    out += ["    endgenerate", "endmodule", ""]
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "csa_trees.sv"), "w").write("\n".join(out))


if __name__ == "__main__":
    main()
