#!/usr/bin/env python3
"""
One GPT-2 launch (test/gpt2/launches/<fmt>/<name>.npz, built by prepare.py)
as a C header for the HammerBlade driver (main.c):

  WIN_WORDS / win[]       the launch's data window, 16-bit words, in DRAM
  PROG_LEN / prog[]       the kernel (gemv or gemm for this K), one
                          16-bit instruction per word
  NB                      thread blocks (8 threads each)
  N_EXP / exp_addr[] / exp_word[]   the bit-exact outputs the kernel must store

  python3 gen_launch.py <launch.npz> <out.h>
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "test", "gpt2"))
import kernels as K                                             # noqa: E402


def c_array(decl, values, per_line=16):
    rows = [", ".join(str(int(v)) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return f"{decl} = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    src, out = sys.argv[1], sys.argv[2]
    d = np.load(src)
    kernel, kc, nb = str(d["kernel"]), int(d["kc"]), int(d["nb"])
    prog = K.gemv_program(kc) if kernel == "gemv" else K.gemm_program(kc)
    words = int(max(d["addr"].max(), d["exp_addr"].max())) + 1
    win = np.zeros(words, dtype=np.uint16)
    win[d["addr"]] = d["word"]
    name = os.path.splitext(os.path.basename(src))[0]
    with open(out, "w") as f:
        f.write(f"// {src}: {kernel} K={kc}, {nb} blocks (generated by gen_launch.py)\n")
        f.write(f'#define LAUNCH_NAME "{name}"\n#define KERNEL_IS_GEMV {int(kernel == "gemv")}\n')
        f.write(f"#define KC {kc}\n#define NB {nb}\n#define WIN_WORDS {words}\n")
        f.write(f"#define PROG_LEN {len(prog)}\n#define N_EXP {len(d['exp_addr'])}\n")
        f.write(c_array("static const unsigned short prog[PROG_LEN]", prog))
        f.write(c_array('unsigned short win[WIN_WORDS] __attribute__((section(".dram"), aligned(64)))', win))
        f.write(c_array('unsigned int exp_addr[N_EXP] __attribute__((section(".dram")))', d["exp_addr"]))
        f.write(c_array('unsigned short exp_word[N_EXP] __attribute__((section(".dram")))', d["exp_word"]))


if __name__ == "__main__":
    main()
